package com.mangareader.core.model

import java.security.MessageDigest

/**
 * Имя файла страницы на диске — одно на весь проект.
 *
 * Ключ считают две стороны: дисковый кеш читалки (он ищет готовый файл)
 * и сетевой источник (он этот файл создаёт). Пока формула была написана
 * в каждой из них отдельно, они расходились — у кеша заголовки
 * склеивались через перевод строки, у источника через `&`, а при пустых
 * заголовках кеш хешировал голый URI, источник — URI с переводом строки
 * на конце. Значит на один и тот же файл выходило два разных имени, и
 * слой «диск» в цепочке память → упреждающая загрузка → диск → сеть
 * не находил ничего никогда: спасало только то, что источник узнавал
 * свой файл сам.
 *
 * Формула живёт здесь, в общем контракте, именно поэтому: у неё два
 * обязательных пользователя, и разойтись им нельзя.
 */
object PageCacheKey {

    /**
     * Заголовки, реально меняющие тело ответа у хостингов картинок.
     *
     * Список закрытый. `Referer`/`Origin` — то, без чего прилетает 403
     * вместо страницы; `Cookie` — сессия, за которой может стоять другой
     * контент. Попади сюда `User-Agent` или случайный `X-Request-Id`,
     * имя менялось бы от запроса к запросу и переиспользования не было
     * бы вовсе.
     */
    val KEYED_HEADERS = setOf("referer", "origin", "cookie")

    /**
     * Ключ = URI плюс значимые заголовки. Имена приводятся к нижнему
     * регистру и сортируются: порядок и регистр заголовков не должны
     * порождать разные имена для одного запроса.
     */
    fun of(uri: String, headers: Map<String, String> = emptyMap()): String {
        val relevant = headers
            .filterKeys { it.lowercase() in KEYED_HEADERS }
            .map { (name, value) -> name.lowercase() + "=" + value }
            .sorted()
        val material = if (relevant.isEmpty()) uri else uri + "\n" + relevant.joinToString("\n")
        return sha1(material)
    }

    fun of(page: PageRef): String = of(page.uri, page.headers)

    /**
     * Подкаталог незавершённых загрузок внутри каталога страниц.
     *
     * Тоже общий, и по той же причине, что и ключ: имя пишет источник,
     * а убирает брошенные огрызки дисковый кеш. Разъедься эти два
     * написания — уборка молча перестала бы находить мусор, и заметно
     * это стало бы только по занятому месту.
     */
    const val INCOMPLETE_DIR = "incomplete"

    private fun sha1(input: String): String =
        MessageDigest.getInstance("SHA-1")
            .digest(input.toByteArray())
            .joinToString("") { "%02x".format(it) }
}
